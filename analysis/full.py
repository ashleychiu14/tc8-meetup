def zz(D,V,th=0.06):
    piv=[(D[0],V[0],'S')]; trend=0; ext=V[0]; ed=D[0]
    for d,v in zip(D[1:],V[1:]):
        if trend>=0 and v>ext: ext,ed=v,d
        elif trend<=0 and v<ext: ext,ed=v,d
        if trend>=0 and v<=ext*(1-th):
            piv.append((ed,ext,'H')); trend=-1; ext,ed=v,d
        elif trend<=0 and v>=ext*(1+th):
            piv.append((ed,ext,'L')); trend=1; ext,ed=v,d
    piv.append((ed,ext,'?'))
    return piv
